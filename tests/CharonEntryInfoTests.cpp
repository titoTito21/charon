static int checks=0,failed=0;
static std::string U8(const char16_t* s) {
    std::string o;
    for(;*s;++s) {
        const unsigned c=*s;
        if(c<0x80)o+=char(c);
        else if(c<0x800) {o+=char(0xc0|c>>6);o+=char(0x80|(c&63));}
        else {o+=char(0xe0|c>>12);o+=char(0x80|((c>>6)&63));o+=char(0x80|(c&63));}
    }
    return o;
}
static void Check(bool ok,const char* what) {++checks;if(!ok)++failed;std::printf("%s %s\n",ok?"PASS":"FAIL",what);}
static void Is(const char16_t* got,const char* want,const char* what) {
    const std::string g=U8(got);++checks;
    if(g==want)std::printf("PASS %s\n",what);else {++failed;std::printf("FAIL %s\n     got:  %s\n     want: %s\n",what,g.c_str(),want);}
}
static std::u16string W(const char* utf8) {
    std::u16string o;const unsigned char* p=(const unsigned char*)utf8;
    while(*p) {
        unsigned c=*p++;
        if(c>=0xe0) {c=(c&15)<<12|(p[0]&63)<<6|(p[1]&63);p+=2;} else if(c>=0xc0) {c=(c&31)<<6|(p[0]&63);++p;}
        o+=char16_t(c);
    }
    return o;
}
static size_t Find(const Entry* e,size_t n,const char* title) {return Match(e,n,W(title).c_str());}
static std::string Say(const Entry& e,bool pl=false) {char16_t out[700];Describe(e,pl,out,700);return U8(out);}
static void Said(const Entry& e,bool pl,const char* want,const char* what) {
    const std::string g=Say(e,pl);++checks;
    if(g==want)std::printf("PASS %s\n",what);else {++failed;std::printf("FAIL %s\n     got:  %s\n     want: %s\n",what,g.c_str(),want);}
}
