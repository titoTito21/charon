"""Generate src/efi/CharonUsbAudioQuirks.h from the Linux kernel's snd-usb-audio quirk data.

Usage: python build-usb-audio-quirks.py LINUX_SOUND_USB_DIR [KERNEL_TAG]

LINUX_SOUND_USB_DIR holds sound/usb/quirks.c and sound/usb/implicit.c of a Linux
release (both "SPDX-License-Identifier: GPL-2.0-or-later", checked here; any
other licence line stops the generator). Only plain data is taken:
  * quirks.c   quirk_flags_table[]            USB ID -> QUIRK_FLAG_* bits
  * implicit.c playback_implicit_fb_quirks[]  USB ID -> implicit feedback kind
No code is copied. The bit numbers are Charon's own (CharonUsbAudioQuirks.h),
only flags that mean something before the system starts are kept.
"""
from pathlib import Path
import re,sys
if len(sys.argv)<2:sys.exit(__doc__)
source=Path(sys.argv[1]);tag=sys.argv[2] if len(sys.argv)>2 else 'unknown'
root=Path(__file__).resolve().parents[1]
KEEP={  # kernel flag -> (Charon bit name, meaning)
 'GET_SAMPLE_RATE':('noRateReadBack','the sampling frequency is not read back'),
 'TX_LENGTH':('lengthHeader','every packet starts with a 4-byte length (not implemented: such a device is refused)'),
 'SKIP_CLOCK_SELECTOR':('skipClockSelector','the clock selector is never written'),
 'IGNORE_CLOCK_SOURCE':('ignoreClockSource','a clock source that cannot be found or read is taken as running at the chosen rate'),
 'CTL_MSG_DELAY':('delay20ms','20 ms after every class request'),
 'CTL_MSG_DELAY_1M':('delay1ms','1 ms after every class request'),
 'CTL_MSG_DELAY_5M':('delay5ms','5 ms after every class request'),
 'IFACE_DELAY':('interfaceDelay','50 ms after SET_INTERFACE'),
 'VALIDATE_RATES':('validateRates','a rate counts only when the clock accepts it (always done by Charon)'),
 'IGNORE_CTL_ERROR':('ignoreControlErrors','errors of mixer requests are ignored (always done by Charon)'),
 'SET_IFACE_FIRST':('interfaceFirst','UAC 2/3: SET_INTERFACE before the clock is set'),
 'GENERIC_IMPLICIT_FB':('implicitFeedback','implicit feedback (the recording endpoint is the clock reference)'),
 'SKIP_IMPLICIT_FB':('noImplicitFeedback','no implicit feedback although the descriptors suggest it'),
 'FORCE_IFACE_RESET':('interfaceReset','alternate setting 0 is set before the stream is started'),
 'FIXED_RATE':('fixedRate','the sampling frequency is not set when the endpoint has one rate'),
 'PLAYBACK_FIRST':('playbackFirst','playback starts before the implicit feedback source'),
}
DROP={'SHARE_MEDIA_DEVICE','ALIGN_TRANSFER','ITF_USB_DSD_DAC','DISABLE_AUTOSUSPEND','DSD_RAW','IFACE_SKIP_CLOSE'}   # no meaning for 16-bit PCM speech before the system starts
def text(name):
    t=(source/name).read_text(encoding='utf-8',errors='replace')
    first=t.splitlines()[0]
    if 'SPDX-License-Identifier: GPL-2.0-or-later' not in first:sys.exit(f'{name}: unexpected licence line: {first}')
    return t
quirks=text('quirks.c');implicit=text('implicit.c')
body=quirks[quirks.index('quirk_flags_table[] = {'):];body=body[:body.index('{} /* terminator */')]
entries=[];unknown=set()
for m in re.finditer(r'(DEVICE_FLG|VENDOR_FLG)\(\s*(0x[0-9a-fA-F]+)\s*,(?:\s*(0x[0-9a-fA-F]+)\s*,)?\s*(?:/\*(.*?)\*/)?\s*((?:QUIRK_FLAG_\w+[\s|]*)+)\)',body,re.S):
    kind,vid,pid,name,flags=m.groups()
    if kind=='VENDOR_FLG':pid='0x0000'
    names=[f for f in re.findall(r'QUIRK_FLAG_(\w+)',flags)]
    unknown|={f for f in names if f not in KEEP and f not in DROP}
    kept=[KEEP[f][0] for f in names if f in KEEP]
    if kept:entries.append((int(vid,16),int(pid,16),kept,' '.join((name or '').split())))
if unknown:sys.exit('quirk flags this generator does not know: '+', '.join(sorted(unknown)))
found=len(re.findall(r'(?:DEVICE_FLG|VENDOR_FLG)\(',body))
play=implicit[implicit.index('playback_implicit_fb_quirks[] = {'):];play=play[:play.index('{} /* terminator */')]
fb=[]
for m in re.finditer(r'IMPLICIT_FB_(GENERIC|FIXED|BOTH|SKIP)_DEV\(\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)[^)]*\)\s*,?\s*(?:/\*(.*?)\*/)?',play,re.S):
    kind,vid,pid,name=m.groups()
    fb.append((int(vid,16),int(pid,16),'noImplicitFeedback' if kind=='SKIP' else 'implicitFeedback',' '.join((name or '').split())))
merged={}
for vid,pid,kept,name in entries:merged[(vid,pid)]=[set(kept),name]
for vid,pid,flag,name in fb:
    e=merged.setdefault((vid,pid),[set(),name]);e[0].add(flag)
order=[v[0] for v in KEEP.values()]
out=['// GENERATED by tools/build-usb-audio-quirks.py - do not edit. GPL-2.0-or-later.',
 '//',
 f'// Device quirks of USB sound devices: plain data from the Linux kernel ({tag}),',
 '// sound/usb/quirks.c (quirk_flags_table) and sound/usb/implicit.c',
 '// (playback_implicit_fb_quirks), both "SPDX-License-Identifier: GPL-2.0-or-later".',
 f'// {found} kernel table entries read, {len(merged)} kept (entries whose flags all concern',
 '// suspend, DSD or the media controller are dropped). product 0 = every device of the vendor.',
 '#pragma once','#include <stddef.h>','#include <stdint.h>','namespace charonusbaudio {','namespace quirk {','enum : uint32_t {']
for i,(k,(name,meaning)) in enumerate(KEEP.items()):out.append(f'    {name}=1u<<{i},   // QUIRK_FLAG_{k}: {meaning}')
out+=['};','}  // namespace quirk','struct QuirkEntry {uint16_t vendor,product;uint32_t flags;};','inline constexpr QuirkEntry quirkTable[]={']
for (vid,pid),(flags,name) in sorted(merged.items(),key=lambda e:(e[0][1]==0,e[0])):   # device matches before vendor matches
    out.append('    {0x%04x,0x%04x,%s},   // %s'%(vid,pid,'|'.join('quirk::'+f for f in order if f in flags),name))
out+=['};',
 '// Flags of a device: its own entry and its vendor\'s entry together (as the kernel does).',
 'inline uint32_t QuirksOf(uint16_t vendor,uint16_t product) {',
 '    uint32_t flags=0;',
 '    for(const QuirkEntry& e:quirkTable)if(e.vendor==vendor && (e.product==product || !e.product))flags|=e.flags;',
 '    return flags;',
 '}','}  // namespace charonusbaudio','']
target=root/'src/efi/CharonUsbAudioQuirks.h'
target.write_text('\n'.join(out),encoding='utf-8',newline='\n')
print(f'{target}: {len(merged)} entries from {found} flag entries and {len(fb)} implicit feedback entries')
