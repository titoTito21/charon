"""Generate src/efi/CharonAaFonts.h: anti-aliased monospace glyph alpha maps (r359).

Usage: python gen-charon-aafonts.py OUTPUT.h FONT.png [FONT.png ...]
Each FONT.png is a rEFInd font strip: 96 glyphs (U+0020..U+007F) side by side,
coverage in the alpha channel (rEFInd 0.14.2 fonts/, the same images rEFInd
embeds as its built-in font). Liberation Mono: SIL OFL 1.1; Ubuntu Mono: UFL 1.0; Nimbus Mono: URW, see licenses.
"""
import sys
from pathlib import Path
from PIL import Image
out=Path(sys.argv[1]);fonts=[Path(p) for p in sys.argv[2:]]
lines=['// Generated by tools/gen-charon-aafonts.py from rEFInd 0.14.2 font strips:',
       '// '+', '.join(p.name for p in fonts)+'.',
       '// Liberation Mono: digitized data Copyright (c) 2010 Google Corporation, Copyright (c) 2012 Red Hat, Inc.;',
       '// SIL Open Font License 1.1, Reserved Font Names Cousine and Liberation',
       '// Ubuntu Mono: Copyright 2010,2011 Canonical Ltd., Ubuntu Font Licence 1.0.',
       '// Nimbus Mono: Copyright URW++, GPL-2.0-or-later with font exception (gsfonts)',
       '// or AGPL-3.0 with font exception (urw-base35); as distributed in rEFInd (GPL-3.0).',
       '// (licenses/liberation-fonts in the Charon package). Alpha 0..255 per pixel.',
       '#pragma once','#include <stdint.h>','namespace hakefi {',
       'struct AaFont {uint8_t width,height;const uint8_t* alpha;};  // glyph g (U+0020+g): alpha[(g*height+y)*width+x]']
names=[]
for i,p in enumerate(fonts):
    im=Image.open(p).convert('RGBA');a=im.split()[3]
    w=im.size[0]//96;h=im.size[1];assert w*96==im.size[0],p
    data=[a.getpixel((g*w+x,y)) for g in range(96) for y in range(h) for x in range(w)]
    name=f'aaFont{i}'
    names.append((name,w,h))
    body=','.join(str(v) for v in data)
    lines.append(f'static const uint8_t {name}Alpha[{len(data)}]={{{body}}};  // {p.name} {w}x{h}')
lines.append('static const AaFont aaFonts[]={'+','.join(f'{{{w},{h},{n}Alpha}}' for n,w,h in names)+'};')
lines.append(f'constexpr unsigned aaFontCount={len(names)};')
lines.append('}')
out.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
print('wrote',out,[(n,w,h) for n,w,h in names])
