"""gen-charon-nvda-setup.py: writes src/efi/CharonWsNvdaSetup.h from src/windows (r407).

What Charon puts in \\charon\\pe on the Windows install media so that NVDA speaks inside Windows Setup:
  nvdape.exe      unpacks NVDA's installer inside Setup's WinPE (src/windows/nvdape.c)
  pestub.dll      stands in for system libraries WinPE lacks and NVDA binds (src/windows/pestub.c)
  pewait.exe      stands in for NVDA's 32-bit helper loader (src/windows/pewait.c)
  peaudio.dll     gives NVDA's sound the category Setup plays (src/windows/peaudio.c)
  charonpe.py     NVDA synthesizer driver: eSpeak NG, loads peaudio.dll first (src/windows/charonpe.py)
  nvda-setup.cmd  unpacks, starts NVDA, falls back to Narrator (src/windows/nvda-setup.cmd)
  nvda.ini        NVDA's configuration for Setup (src/windows/nvda.ini)
The three programs are compiled here with the LLVM that builds Charon (x86-64 Windows, kernel32
only, no C runtime, reproducible) and stored as bytes; the two texts as strings with @LANG@ left
for Charon to fill in. Run from anywhere after editing a file in src/windows.
Environment: CHARON_LLVM (default ../work/llvm-23.1.5/bin relative to the repository container).
GPL-2.0-or-later."""
import hashlib,os,subprocess,sys,tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
container=root.parents[1]
llvm=Path(os.environ.get('CHARON_LLVM',container/'work/llvm-23.1.5/bin'))
clang=str(llvm/'clang.exe');link=str(llvm/'lld-link.exe')
src=root/'src'/'windows'
compile_flags=['--target=x86_64-pc-windows-msvc','-Os','-Wall','-Wextra','-Werror','-ffreestanding','-fno-stack-protector','-fno-builtin','-mno-stack-arg-probe']
def run(*a,cwd):subprocess.run([str(x) for x in a],check=True,cwd=cwd)
def build(tmp,name,kind,libs=()):
    run(clang,*compile_flags,'-c',src/(name+'.c'),'-o',name+'.obj',cwd=tmp)
    if kind=='dll':
        out=name+'.dll';run(link,'-dll','-nodefaultlib','-entry:_DllMainCRTStartup','-subsystem:windows','-Brepro','-out:'+out,name+'.obj',*libs,cwd=tmp)
    else:
        out=name+'.exe';run(link,'-nodefaultlib','-entry:entry','-subsystem:'+kind,'-Brepro','-out:'+out,name+'.obj','kernel32.lib',cwd=tmp)
    return (Path(tmp)/out).read_bytes()
def text_literal(data):
    lines=[]
    for line in data.decode('ascii').replace('\r\n','\n').rstrip('\n').split('\n'):
        lines.append('    "'+line.replace('\\','\\\\').replace('"','\\"')+'\\r\\n"')
    return '\n'.join(lines)+';'
def byte_literal(data):
    return '\n'.join('    '+','.join('0x%02x'%b for b in data[i:i+32])+',' for i in range(0,len(data),32))
with tempfile.TemporaryDirectory() as tmp:
    run(link,'-lib','-def:'+str(src/'kernel32.def'),'-machine:x64','-out:kernel32.lib',cwd=tmp)
    run(link,'-lib','-def:'+str(src/'ole32.def'),'-machine:x64','-out:ole32.lib',cwd=tmp)
    programs=[('nvdaPeUnpack','nvdape.exe',build(tmp,'nvdape','console'),'unpacks NVDA\'s installer inside Windows Setup'),
              ('nvdaPeStub','pestub.dll',build(tmp,'pestub','dll'),'stands in for system libraries Setup\'s WinPE lacks'),
              ('nvdaPeWait','pewait.exe',build(tmp,'pewait','windows'),'stands in for NVDA\'s 32-bit helper loader'),
              ('nvdaPeAudio','peaudio.dll',build(tmp,'peaudio','dll',('kernel32.lib','ole32.lib')),'gives NVDA\'s sound the category Setup plays')]
lines=['// Generated by tools/gen-charon-nvda-setup.py from src/windows: do not edit; edit the sources there.',
       '#pragma once','#include <stdint.h>','namespace hakefi {','namespace ws {','namespace install {']
for name,file,data,what in programs:
    lines.append('// '+file+': '+what+'. SHA-256 '+hashlib.sha256(data).hexdigest())
    lines.append('inline const uint8_t '+name+'[]={')
    lines.append(byte_literal(data));lines.append('};')
for name,file,what in (('nvdaPeScript','nvda-setup.cmd','run by the answer file in the windowsPE pass; @LANG@ is en, or pl when the Windows being installed is Polish'),
                       ('nvdaPeConfig','nvda.ini','NVDA\'s configuration inside Setup; @LANG@ as above'),
                       ('nvdaPeSynth','charonpe.py','NVDA synthesizer driver for Setup: eSpeak NG, loads peaudio.dll first')):
    data=(src/file).read_bytes()
    lines.append('// '+file+': '+what+'.')
    lines.append('inline const char '+name+'[]=')
    lines.append(text_literal(data))
lines+=['}  // namespace install','}  // namespace ws','}  // namespace hakefi','']
(root/'src'/'efi'/'CharonWsNvdaSetup.h').write_text('\n'.join(lines),encoding='ascii',newline='\n')
print('PASS',', '.join('%s %d bytes'%(f,len(d)) for _,f,d,_ in programs))
