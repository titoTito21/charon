"""Generate src/efi/CharonGlyphs.h: 8x16 GNU Unifont bitmaps for Charon's OCR (r358).

Usage: python gen-charon-glyphs.py unifont_all-VERSION.hex.gz [unicode.pf2]
Selected ranges: printable ASCII, Latin-1, Latin Extended-A (Polish letters),
arrows and geometric shapes used in menus, box drawing and blocks.
With a GRUB unicode.pf2 the generator renders each selected PF2 glyph into an
8x16 cell (font ascent) and reports how many are bit-identical to Unifont, so
the template set is checked against the font GRUB's gfxterm actually draws.
GNU Unifont: GPL-2.0-or-later with the GNU font embedding exception, or OFL-1.1.
"""
import gzip,struct,sys
from pathlib import Path
ranges=[(0x20,0x7e),(0xa0,0x17f),(0x2190,0x2193),(0x25b2,0x25b2),(0x25b6,0x25b6),(0x25ba,0x25ba),(0x25bc,0x25bc),(0x25c0,0x25c0),(0x25c4,0x25c4),(0x2500,0x259f),(0x2022,0x2022),(0x2026,0x2026)]
wanted={c for a,b in ranges for c in range(a,b+1)}
glyphs={}
with gzip.open(sys.argv[1],'rt',encoding='ascii') as f:
    for line in f:
        code,bits=line.strip().split(':')
        code=int(code,16)
        if code in wanted and len(bits)==32:glyphs[code]=bytes.fromhex(bits)
if len(sys.argv)>2:
    data=Path(sys.argv[2]).read_bytes();at=0;sections={}
    while at+8<=len(data):
        name=data[at:at+4];length=struct.unpack('>I',data[at+4:at+8])[0]
        if name==b'FILE':length=4
        if name==b'DATA':sections[name]=at+8;break
        sections[name]=data[at+8:at+8+length];at+=8+length
    ascent=struct.unpack('>H',sections[b'ASCE'])[0]
    index={}
    chix=sections[b'CHIX']
    for i in range(0,len(chix),9):
        code,flags,offset=struct.unpack('>IBI',chix[i:i+9]);index[code]=offset
    same=differ=0
    for code,bits in glyphs.items():
        if code not in index:continue
        o=index[code];w,h,xo,yo,dw=struct.unpack('>HHhhh',data[o:o+10]);raw=data[o+10:o+10+(w*h+7)//8]
        if dw!=8:continue
        cell=[0]*16
        for y in range(h):
            for x in range(w):
                bit=y*w+x
                if raw[bit//8]&(0x80>>(bit%8)):
                    cy=ascent-yo-h+y;cx=xo+x
                    if 0<=cy<16 and 0<=cx<8:cell[cy]|=0x80>>cx
        if bytes(cell)==bits:same+=1
        else:differ+=1
    print(f'PF2 ascent {ascent}: identical {same}, different {differ}',file=sys.stderr)
codes=sorted(glyphs)
out=['// Generated by tools/gen-charon-glyphs.py from GNU Unifont '+Path(sys.argv[1]).name+'.',
     '// GNU Unifont: GPL-2.0-or-later with the font embedding exception, or OFL-1.1.',
     '#pragma once','#include <stdint.h>','namespace hakefi {',
     f'constexpr unsigned glyphCount={len(codes)};',
     'static const uint16_t glyphCodes[glyphCount]={'+','.join(f'0x{c:04x}' for c in codes)+'};',
     'static const uint8_t glyphRows[glyphCount][16]={']
out+=['    {'+','.join(f'0x{b:02x}' for b in glyphs[c])+'},' for c in codes]
out+=['};','}','']
Path(__file__).resolve().parents[1].joinpath('src/efi/CharonGlyphs.h').write_text('\n'.join(out),encoding='utf-8',newline='\n')
print(len(codes),'glyphs')
