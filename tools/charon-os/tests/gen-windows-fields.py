#!/usr/bin/env python3
"""Write windows/CharonOs.Fields.ps1 from tests/charon_fields.py (the one table of
Charon's settings rows, their record bytes and their Polish and English names).
Usage: python gen-windows-fields.py [--check]   (--check: exit 1 when the file differs)"""
import sys
from pathlib import Path
here = Path(__file__).resolve().parent
sys.path.insert(0, str(here))
sys.dont_write_bytecode = True
import charon_fields as f

def q(text):
    return "'" + str(text).replace("'", "''") + "'"

out = ["# Generated by tools/charon-os/tests/gen-windows-fields.py from charon_fields.py. Do not edit by hand.",
       "# Charon's settings rows: record member, bits, first record format, Polish and English names",
       "# (src/efi/CharSettings.h, src/efi/BootMenu.h labelFor, src/efi/BootMenuModel.h).",
       "$script:CharonMembers = @(" + ', '.join(q(m) for m in f.MEMBERS) + ")",
       "$script:CharonDefaults = @{ " + '; '.join('%s = %d' % (m, f.DEFAULTS[m]) for m in f.MEMBERS) + " }",
       "$script:CharonDefaultsAB = @{ " + '; '.join('%s = %d' % kv for kv in f.DEFAULTS_AB.items()) + " }",
       "$script:CharonDefaultsC = @{ " + '; '.join('%s = %d' % kv for kv in f.DEFAULTS_C.items()) + " }",
       "$script:CharonMemberSince = @{ " + '; '.join('%s = %s' % (m, q(f.MEMBER_SINCE[m])) for m in f.MEMBERS) + " }",
       "$script:CharonAutoDelays = @(" + ', '.join(str(v) for v in f.AUTO_DELAYS) + ")",
       "$script:CharonPages = @("]
out += ["    @{ Id = %s; En = %s; Pl = %s }%s" % (q(i), q(en), q(pl), ',' if n + 1 < len(f.PAGES) else '') for n, (i, en, pl) in enumerate(f.PAGES)]
out += [")", "$script:CharonRows = @("]
for n, r in enumerate(f.ROWS):
    parts = ["Id = %s" % q(r['id']), "Page = %s" % q(r['page']), "Kind = %s" % q(r['kind']), "Member = %s" % q(r['member']),
             "Since = %s" % q(r['since']), "En = %s" % q(r['en']), "Pl = %s" % q(r['pl'])]
    if r['kind'] == 'check':
        parts.append("Mask = %d" % r['mask'])
    elif r['kind'] == 'choice':
        parts.append("Shift = %d" % r['shift']); parts.append("Mask = %d" % r['mask'])
        parts.append("Choices = @(" + ', '.join("@(%d, %s, %s)" % (v, q(en), q(pl)) for v, en, pl in r['choices']) + ")")
    else:
        parts.append("Low = %d" % r['low']); parts.append("High = %d" % r['high']); parts.append("Unit = %s" % q(r['unit']))
    out.append("    @{ " + '; '.join(parts) + " }" + (',' if n + 1 < len(f.ROWS) else ''))
out += [")", "$script:CharonLingerNoteEn = " + q(f.LINGER_NOTE_EN), "$script:CharonLingerNotePl = " + q(f.LINGER_NOTE_PL), ""]
data = ('﻿' + '\r\n'.join(out)).encode('utf-8')
target = here.parent / 'windows' / 'CharonOs.Fields.ps1'
if '--check' in sys.argv:
    sys.exit(0 if target.exists() and target.read_bytes() == data else 1)
target.write_bytes(data)
print('written', target)
