"""Generate src/efi/CharonPf2Fonts.h from GRUB PF2 bitmap fonts (r367).

GRUB themes draw menus with PF2 fonts made by grub-mkfont (Debian's
grub-theme-starfield: DejaVu Sans 10/12/14/16 and Bold 14). The reader keeps
the glyphs of the characters it recognizes (ASCII, Polish letters, a few
typographic marks) as 1-bit bitmaps with their metrics.
  python gen-charon-pf2fonts.py OUT.h FONT.pf2 [FONT.pf2 ...]
"""
import struct,sys
from pathlib import Path
CHARS=[chr(c) for c in range(0x21,0x7f)]+list('ąćęłńóśźżĄĆĘŁŃÓŚŹŻ’“”–—…©®°')+[' ']

def read_pf2(path):
    d=Path(path).read_bytes();pos=0;meta={};chix=None;
    while pos+8<=len(d):
        name=d[pos:pos+4];length=struct.unpack('>I',d[pos+4:pos+8])[0]
        if name==b'DATA':break
        body=d[pos+8:pos+8+length]
        if name==b'CHIX':chix=body
        else:meta[name]=body
        pos+=8+length
    assert meta[b'FILE']==b'PFF2',path
    index={}
    for k in range(0,len(chix),9):
        code,flags,offset=struct.unpack('>IBI',chix[k:k+9]);index[code]=offset
    glyphs={}
    for ch in CHARS:
        off=index.get(ord(ch))
        if off is None:continue
        w,h,xo,yo,dw=struct.unpack('>HHhhh',d[off:off+10])
        bits=d[off+10:off+10+(w*h+7)//8]
        glyphs[ch]=(w,h,xo,yo,dw,bits)
    name=meta[b'NAME'].rstrip(b'\0').decode()
    return name,struct.unpack('>H',meta[b'PTSZ'])[0],struct.unpack('>H',meta[b'ASCE'])[0],glyphs

def main(out,*fonts):
    lines=['// Generated by tools/gen-charon-pf2fonts.py (r367) from GRUB PF2 fonts of',
           "// Debian's grub-theme-starfield (DejaVu Sans; Bitstream Vera licence, DejaVu",
           '// changes public domain: licenses/dejavu-fonts). Glyph bitmaps, not fonts.',
           '#pragma once','#include <stdint.h>','namespace hakefi {',
           'struct Pf2Glyph {char16_t code;uint8_t width,height;int8_t xOffset,yOffset,advance;uint32_t bits;};',
           'struct Pf2Font {const char* name;uint8_t pointSize,ascent;uint16_t count;const Pf2Glyph* glyphs;const uint8_t* bits;};']
    table=[]
    for n,path in enumerate(fonts):
        name,size,ascent,glyphs=read_pf2(path)
        data=bytearray();entries=[]
        for ch in CHARS:
            if ch not in glyphs:continue
            w,h,xo,yo,dw,bits=glyphs[ch]
            entries.append('{0x%04x,%d,%d,%d,%d,%d,%d}'%(ord(ch),w,h,xo,yo,dw,len(data)));data+=bits
        lines.append('inline constexpr Pf2Glyph pf2Glyphs%d[]={%s};'%(n,','.join(entries)))
        hexes=','.join('0x%02x'%b for b in data) or '0'
        lines.append('inline constexpr uint8_t pf2Bits%d[]={%s};'%(n,hexes))
        table.append('{"%s",%d,%d,%d,pf2Glyphs%d,pf2Bits%d}'%(name,size,ascent,len(entries),n,n))
    lines.append('inline constexpr Pf2Font pf2Fonts[]={%s};'%','.join(table))
    lines.append('inline constexpr unsigned pf2FontCount=%d;'%len(table))
    lines.append('}  // namespace hakefi')
    Path(out).write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print('wrote',out,len(table),'fonts',Path(out).stat().st_size,'bytes')

if __name__=='__main__':main(*sys.argv[1:])
