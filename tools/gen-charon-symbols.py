#!/usr/bin/env python3
"""Generate src/efi/CharonSymbols.h from NVDA's original locale data (r390).

Inputs (NVDA source tree, pinned commit, GPL-2.0):
  source/locale/<lang>/symbols.dic            punctuation and symbol names
  source/locale/<lang>/characterDescriptions.dic  phonetic alphabet

Like NVDA, a locale's symbols fall back to the English ones for fields and
identifiers the locale file does not define. Only what Charon's freestanding
processor implements is emitted: simple symbols of 1..4 UTF-16 units and the
complex identifiers whose patterns are coded by hand in CharonSpeechText.h.

Usage: python3 tools/gen-charon-symbols.py NVDA_SOURCE_DIR [OUT]
"""
import sys
from pathlib import Path

LEVELS = {"none": 0, "some": 1, "most": 2, "all": 3, "char": 4}
PRESERVE = {"never": 0, "always": 1, "norep": 2}
COMPLEX = [". sentence ending", "! sentence ending", "? sentence ending",
           "; phrase ending", ": phrase ending", "multiple .",
           "decimal point", "in-word '", "negative number"]
ESCAPES = {"\\0": "\0", "\\t": "\t", "\\n": "\n", "\\r": "\r", "\\f": "\f", "\\#": "#", "\\\\": "\\"}


def parse_symbols(path):
    complex_ids, symbols = [], {}
    section = None
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.rstrip("\r\n")
        if not line or line.startswith("#"):
            continue
        if line in ("complexSymbols:", "symbols:"):
            section = line[:-1]
            continue
        fields = line.split("\t")
        if section == "complexSymbols":
            complex_ids.append(fields[0])
            continue
        if section != "symbols":
            continue
        ident = ESCAPES.get(fields[0], fields[0])
        # The display name after " # " is not spoken.
        fields = [fields[0]] + [f for f in fields[1:] if not f.lstrip().startswith("#")]
        repl = fields[1] if len(fields) > 1 and fields[1] != "-" else None
        level = LEVELS.get(fields[2].strip()) if len(fields) > 2 and fields[2].strip() not in ("", "-") else None
        pres = PRESERVE.get(fields[3].strip()) if len(fields) > 3 and fields[3].strip() not in ("", "-") else None
        symbols[ident] = (repl, level, pres)
    return complex_ids, symbols


def merged(locale_dir, lang):
    _, en = parse_symbols(locale_dir / "en" / "symbols.dic")
    _, own = parse_symbols(locale_dir / lang / "symbols.dic") if lang != "en" else ([], en)
    out = {}
    for ident in list(en) + [i for i in own if i not in en]:
        r, l, p = own.get(ident, (None, None, None))
        er, el, ep = en.get(ident, (None, None, None))
        repl = r if r is not None else er
        level = l if l is not None else (el if el is not None else 3)
        pres = p if p is not None else (ep if ep is not None else 0)
        out[ident] = (repl or "", level, pres)
    return out


def phonetics(locale_dir, lang):
    table = {}
    for raw in (locale_dir / lang / "characterDescriptions.dic").read_text(encoding="utf-8-sig").splitlines():
        if not raw or raw.startswith("#"):
            continue
        fields = raw.split("\t")
        if len(fields) >= 2 and len(fields[0]) == 1:
            table[fields[0]] = fields[1]
    return table


def u16(text):
    out = []
    for ch in text:
        cp = ord(ch)
        if cp > 0xFFFF:
            cp -= 0x10000
            out += [0xD800 | (cp >> 10), 0xDC00 | (cp & 0x3FF)]
        else:
            out.append(cp)
    return out


def literal(text):
    # Fixed-length escapes only (a \x escape would swallow following hex letters).
    out = []
    for ch in text:
        c = ord(ch)
        if c < 0x20 or 0x7f <= c < 0xa0 or c in (0x22, 0x5c, 0x3f):
            out.append(f"\\{c:03o}")
        elif c <= 0x7e:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append(f"\\u{c:04x}")
        else:
            out.append(f"\\U{c:08x}")
    return "u\"" + "".join(out) + "\""


def main():
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "src/efi/CharonSymbols.h"
    locale_dir = src / "source" / "locale"
    lines = ["// Generated by tools/gen-charon-symbols.py from NVDA's original locale data",
             "// (source/locale/{en,pl}/symbols.dic and characterDescriptions.dic, NVDA",
             "// commit pinned in UPSTREAM.json; GPL-2.0, NVDA contributors). Do not edit.",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "namespace hakefi::symbols {",
             "// level: 0 none, 1 some, 2 most, 3 all, 4 char; preserve: 0 never, 1 always, 2 norep",
             "struct Symbol {const char16_t* id;uint8_t length,level,preserve;const char16_t* name;};",
             "struct Complex {uint8_t kind,level,preserve;const char16_t* name;};",
             "struct Phonetic {char16_t ch;const char16_t* name;};",
             "enum ComplexKind : uint8_t {sentenceDot,sentenceBang,sentenceQuestion,phraseSemicolon,phraseColon,multipleDots,decimalPoint,inWordApostrophe,negativeNumber,complexCount};"]
    for lang in ("pl", "en"):
        table = merged(locale_dir, lang)
        simple = [(i, v) for i, v in table.items() if i not in COMPLEX and 1 <= len(u16(i)) <= 4]
        simple.sort(key=lambda item: (-len(u16(item[0])), u16(item[0])))   # longest first, then by code
        lines.append(f"inline constexpr Symbol simple_{lang}[]={{")
        for ident, (repl, level, pres) in simple:
            lines.append(f"    {{{literal(ident)},{len(u16(ident))},{level},{pres},{literal(repl)}}},")
        lines.append("};")
        lines.append(f"inline constexpr size_t simpleCount_{lang}=sizeof(simple_{lang})/sizeof(simple_{lang}[0]);")
        lines.append(f"inline constexpr Complex complex_{lang}[]={{")
        for kind, ident in enumerate(COMPLEX):
            repl, level, pres = table.get(ident, ("", 3, 0))
            lines.append(f"    {{{kind},{level},{pres},{literal(repl)}}},   // {ident}")
        lines.append("};")
        ph = phonetics(locale_dir, lang)
        lines.append(f"inline constexpr Phonetic phonetic_{lang}[]={{")
        for ch in sorted(ph):
            lines.append(f"    {{{literal(ch)}[0],{literal(ph[ch])}}},")
        lines.append("};")
        lines.append(f"inline constexpr size_t phoneticCount_{lang}=sizeof(phonetic_{lang})/sizeof(phonetic_{lang}[0]);")
    lines.append("}  // namespace hakefi::symbols")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(out, sum(1 for l in lines if l.startswith("    {")), "entries")


if __name__ == "__main__":
    main()
