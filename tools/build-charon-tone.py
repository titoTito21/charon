"""build-charon-tone.py OUTDIR: builds src/linux/charon-tone.c as a static x86-64 Linux program
(no C library) with the LLVM tool chain in work/llvm-23.1.5 and writes
  OUTDIR/charon-tone               the program
  src/efi/CharonToneBinary.h       the same bytes as a C array, compiled into CHARON.EFI
Run from the source root. GPL-2.0-or-later."""
import subprocess,sys,hashlib
from pathlib import Path
root=Path(__file__).resolve().parent.parent
llvm=root.parent/'llvm-23.1.5'/'bin'
out=Path(sys.argv[1]).resolve();out.mkdir(parents=True,exist_ok=True)
src=root/'src'/'linux'/'charon-tone.c'
obj=out/'charon-tone.o';elf=out/'charon-tone'
subprocess.run([str(llvm/'clang.exe'),'--target=x86_64-unknown-linux-gnu','-std=c11','-Os','-ffreestanding','-fno-stack-protector',
    '-fno-pic','-fno-asynchronous-unwind-tables','-fno-builtin','-mno-red-zone','-Wall','-Wextra','-Werror','-c',str(src),'-o',str(obj)],check=True)
subprocess.run([str(llvm/'ld.lld.exe'),'-static','-nostdlib','--gc-sections','-z','noexecstack','--build-id=none','-s','-e','_start','-o',str(elf),str(obj)],check=True)
data=elf.read_bytes()
assert data[:4]==b'\x7fELF' and data[4]==2 and data[18]==62,'not an x86-64 ELF'
lines=['// Generated by tools/build-charon-tone.py from src/linux/charon-tone.c: do not edit.',
       '// The static Linux program charon-tone, written beside Charon\'s scripts in an installed system.',
       '// sha256 '+hashlib.sha256(data).hexdigest(),'#pragma once','#include <stdint.h>','namespace hakefi {',
       'inline const uint8_t charonToneBinary[%d]={'%len(data)]
for i in range(0,len(data),24):lines.append(','.join(str(b) for b in data[i:i+24])+',')
lines+=['};','}  // namespace hakefi','']
(root/'src'/'efi'/'CharonToneBinary.h').write_text('\n'.join(lines),encoding='ascii',newline='\n')
print('PASS',len(data),'bytes',hashlib.sha256(data).hexdigest())
