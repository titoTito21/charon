"""Freeze actual PL rule/lexicon data, without importing Titan's synthesis engine."""
import importlib.util,json,sys,types,hashlib
from generate_data import HERE,VOICE
sys.dont_write_bytecode=True
package=types.ModuleType('_tvox_original');package.__path__=[str(VOICE)]
sys.modules[package.__name__]=package
def load(name):
    spec=importlib.util.spec_from_file_location(package.__name__+'.'+name,VOICE/(name+'.py'))
    module=importlib.util.module_from_spec(spec);sys.modules[spec.name]=module;spec.loader.exec_module(module)
    return module
phonemes=load('phonemes');original=load('g2p_pl')
def literal(s):return 'U'+json.dumps(s,ensure_ascii=False)
def generate():
    lines=['/* Original Titan Voice data, generated by generate_pl.py; MIT-0. */']
    for name,value in vars(original).items():
        if not name.isupper() or name.startswith('_'):continue
        if isinstance(value,(set,tuple)) and all(isinstance(x,str) for x in value):
            values=sorted(value) if isinstance(value,set) else value
            lines.append('static const S '+name+'[]={'+','.join(map(literal,values))+'};')
        elif isinstance(value,dict) and all(isinstance(k,str) and isinstance(v,str) for k,v in value.items()):
            items=sorted(value.items(),key=lambda kv:-len(kv[0])) if name=='SOFT_I' else value.items()
            lines.append('static const Pair '+name+'[]={'+','.join('{'+literal(k)+','+literal(v)+'}' for k,v in items)+'};')
        elif name=='DIGRAPHS':
            lines.append('static const Pair '+name+'[]={'+','.join('{'+literal(k)+','+literal(v)+'}' for k,v in value)+'};')
    lex=original._lexicon()
    lines.append('static const S KNOWN_PL_PHONES[]={'+','.join(map(literal,sorted(phonemes.P_PL)))+'};')
    lines.append('static const Pair LEXICON[]={'+','.join('{'+literal(k)+','+literal(' '.join(v))+'}' for k,v in sorted(lex.items()))+'};')
    lines.append('static const Pair LOWER[]={'+','.join('{'+literal(chr(n))+','+literal(chr(n).lower())+'}' for n in range(0x110000) if chr(n)!=chr(n).lower())+'};')
    (HERE/'tvox_pl_data.inc').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    sources=[VOICE/'g2p_pl.py',VOICE/'phonemes.py',VOICE/'data'/'pl_lexicon.tsv']
    (HERE/'PL-PROVENANCE.json').write_text(json.dumps({'unicode_version':__import__('unicodedata').unidata_version,
        'sha256':{str(p.relative_to(VOICE)).replace('\\','/'):hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}},indent=2)+'\n')
    (HERE/'WIKIPRON-NOTICE.txt').write_text('\n'.join(line for line in (VOICE/'data'/'pl_lexicon.tsv').read_text(encoding='utf-8').splitlines() if line.startswith('#'))+'\n',encoding='utf-8')
if __name__=='__main__':generate()
