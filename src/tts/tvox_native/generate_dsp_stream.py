"""Mechanical resumable-frame extraction of original TVox DSP; no DSP redesign.

r385: also writes tvox_dsp_mit.c, the upstream DSP without eSpeak NG code (see strip_espeak).
MIT-0.
"""
import hashlib,json,re
from pathlib import Path
HERE=Path(__file__).resolve().parent
source=(HERE/'upstream/tvox_dsp.c').read_text()
NL='\n'
# r385: Charon carries no eSpeak NG code. The 'clear' timbre (eSpeak NG's
# pk_shape2 table and its PeaksToHarmspect harmonic spectrum, bass ramp,
# tone_adjust on harmonics, harmonic-1 gain, sign switch; GPL-3.0-or-later,
# Duddington/Dunn) is cut out of the upstream text; KG_HARM is ignored
# (Charon's Adam voices never set it, generate_dsp_adapter.py asserts that),
# so everything left is Titan Voice's own code or openevv's MIT source.
def strip_espeak(text):
    start=text.index('/*'+NL+" * The 'clear' timbre")
    end=text.index('};'+NL,text.index('static const unsigned char pk_shape2'))+3
    text=text[:start]+text[end:]
    old='    int harm = g[KG_HARM] != 0.0, hk = 0, hloop = 0;'+NL
    assert text.count(old)==1
    text=text.replace(old,"    int harm = 0, hk = 0, hloop = 0;   /* r385: the 'clear' timbre is not part of Charon */"+NL)
    for line in ('    double hwscale = g[KG_HWSCALE], hwbase = g[KG_HWBASE], htop = g[KG_HTOP], hscale = g[KG_HSCALE];'+NL,'    double hslope = g[KG_HSLOPE];'+NL):
        assert text.count(line)==1
        text=text.replace(line,'')
    old='    int resync = 1, hcount = 0;'+NL
    assert text.count(old)==1
    text=text.replace(old,old+'    (void)hk; (void)hcount;'+NL)
    head='                if (harm && hcount++ % 2 == 0) {'
    assert text.count(head)==1
    i=text.index(head);depth=0;j=i
    while True:
        c=text[j]
        if c=='{':depth+=1
        elif c=='}':
            depth-=1
            if not depth:break
        j+=1
    text=text[:i].rstrip(' ')+text[j+2:]   # the block and its newline
    for word in ('eSpeak','pk_shape2','PeaksToHarmspect','Duddington','tone_adjust','Reece'):
        assert word not in text,word
    return text
source=strip_espeak(source)
(HERE/'tvox_dsp_mit.c').write_text("/* Generated by generate_dsp_stream.py from Titan Voice's tvox_dsp.c without the"+NL
    +" * eSpeak NG-derived 'clear' timbre. MIT-0 (Titan Voice); glottal source after openevv (MIT). */"+NL+source,encoding='utf-8',newline=NL)
start=source.index('EXPORT int klatt_render(')
end=source.index('\n/*\n * pcm16',start)
prefix=source[:source.index('EXPORT int klatt_frame(')]+source[source.index('/*\n * klatt_render'):start]
body=source[start:end]
names=('r1a r1b r2a r2b r3a r3b r4a r4b r5a r5b r6a r6b npa npb nzx1 nzx2 '
 'p2a p2b p3a p3b p4a p4b p5a p5b p6a p6b tilt_y shelf_lp nlp rad_prev dc_x dc_y '
 'T0 pos Te scale per_amp t_sec av0 ah0 af0 prev_av prev_ah prev_af').split()
ints='odd have_prev have_prevp hk hloop resync hcount'.split()
arrays={'sst':('double',64),'pv':('double',16),'p':('double',16),
 **{n:('float','H_MAX + 1') for n in ['ha','hd','hc','hs','rcs','rsn']}}
state='typedef struct { int initialized,frame; unsigned long long rs; const double *tab;\n'
state+='double '+','.join(names)+';\nint '+','.join(ints)+';\n'
state+=''.join(t+' '+n+'['+str(count)+'];\n' for n,(t,count) in arrays.items())+'} RenderState;\n'
allnames=names+ints+['rs','tab']
load='if(ctx->initialized) {\n'+''.join(n+'=ctx->'+n+';\n' for n in allnames)
save='ctx->initialized=1;ctx->frame=fn;\n'+''.join('ctx->'+n+'='+n+';\n' for n in allnames)
for n,(t,count) in arrays.items():
 load+='for(k=0;k<'+str(count)+';k++) '+n+'[k]=ctx->'+n+'[k];\n'
 save+='for(k=0;k<'+str(count)+';k++) ctx->'+n+'[k]='+n+'[k];\n'
load+='}\n'
body=body.replace('EXPORT int klatt_render(int nframes,','static int render_frame(RenderState *ctx, int nframes,',1)
body=body.replace('    if (nshelf > 16)',load+'    if (nshelf > 16)',1)
body=body.replace('for (fn = 0; fn < nframes; fn++)','for (fn = ctx->frame; fn < nframes && fn < ctx->frame + 1; fn++)',1)
body=body.replace('            continue;','            continue;',1) # loop increment still reaches state save
body=body.replace('    return w;',save+'    return w;',1)
target=HERE/'tvox_dsp_stream_core.inc'
target.write_text("/* Generated from Titan Voice's tvox_dsp.c without the eSpeak NG-derived 'clear' timbre; MIT-0. */\n"+prefix+state+body,encoding='utf-8',newline='\n')
(HERE/'DSP-STREAM-PROVENANCE.json').write_text(json.dumps({'upstream_sha256':hashlib.sha256((HERE/'upstream/tvox_dsp.c').read_bytes()).hexdigest(),
    'mit_sha256':hashlib.sha256((HERE/'tvox_dsp_mit.c').read_bytes()).hexdigest(),'generated_sha256':hashlib.sha256(target.read_bytes()).hexdigest()},indent=2)+'\n')
