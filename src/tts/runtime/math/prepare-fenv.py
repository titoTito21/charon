"""Adapt only musl x64 leaf stack scratch to EFI's no-red-zone ABI."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parent
source=root/'musl/src/fenv/x86_64/fenv.s'
original=source.read_text()
result=original
for name in ('feclearexcept','feraiseexcept'):
    start=result.index(name+':\n');end=result.index('\n.global',start)
    block=result[start:end]
    assert block.count('\tret')==1 and '-8(%rsp)' in block
    block=block.replace(name+':\n',name+':\n\tsub $8,%rsp\n',1)
    block=block.replace('-8(%rsp)','(%rsp)').replace('\tret','\tadd $8,%rsp\n\tret')
    result=result[:start]+block+result[end:]
assert '-8(%rsp)' not in result
result='# Generated by prepare-fenv.py; only stack scratch ABI differs from musl.\n'+result
result+='\n.section .note.GNU-stack,"",@progbits\n'
output=root/'fenv-no-red-zone.s'
output.write_text(result,newline='\n')
(root/'fenv-adaptation.json').write_text(json.dumps({'original_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
    'adapted_sha256':hashlib.sha256(output.read_bytes()).hexdigest(),
    'changes':'feclearexcept/feraiseexcept: reserve 8 stack bytes, address reserved slot instead of red zone, restore stack before return; GNU-stack note. No floating-point instruction changes.'},indent=2)+'\n',newline='\n')
