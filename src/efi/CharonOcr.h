class PixelOcr {
public:
    struct Cell {char16_t ch;uint32_t foreground,background;bool ink;};
    // r386: per-band grid search (GRUB themes, text over pictures); off for
    // boot managers that Charon reads with their own fonts.
    bool bandsEnabled=true,bandsAlways=false;  // always: GRUB (its themes put every label on its own grid)
    // pixels: 0x00RRGGBB rows of `stride` pixels; (left,top) = screen position
    // of pixels[0]. emit(char16_t* text,size_t screenX,size_t screenY,uint32_t fg,uint32_t bg)
    // is called per run of cells sharing a background on each text line.
    // Returns the number of recognized non-blank cells.
    template<class Emit> size_t Recognize(const uint32_t* pixels,size_t width,size_t height,size_t stride,size_t left,size_t top,Emit emit) {
        return Recognize(pixels,width,height,stride,left,top,emit,[]() {});
    }
    // r368: `idle` runs between text rows (the reader's timer feeds audio).
    template<class Emit,class Idle> size_t Recognize(const uint32_t* pixels,size_t width,size_t height,size_t stride,size_t left,size_t top,Emit emit,Idle idle) {
        // r386: text over a picture is a minority of a whole screen's inked
        // cells, and graphical menus (GRUB themes) place every label at its
        // own pixel position, so one 8x16 grid does not fit them all. After
        // the whole-area pass, bands of 32 rows (16 apart, so every 16-row
        // line lies whole in one) that gave no text and hold ink get a grid
        // search of their own. A band of picture alone still yields nothing.
        constexpr size_t maxBands=1024;
        static uint8_t covered[maxBands];
        const size_t bands=height>=32?(height-16)/16:0;
        for(size_t i=0;i<bands && i<maxBands;++i)covered[i]=0;
        // Only lines with a letter or digit cover a band: picture junk
        // ("?" cells) must not hide a real line next to it.
        bool anyWord=false;
        auto mark=[&](const char16_t* text,size_t y) {
            bool word=false;
            for(const char16_t* p=text;*p && !word;++p)word=(*p>=u'0' && *p<=u'9') || (*p>=u'A' && *p<=u'Z') || (*p>=u'a' && *p<=u'z') || (*p>=0xc0 && *p<0x2500);
            if(!word)return;
            anyWord=true;
            const size_t local=y>=top?y-top:0;
            for(size_t i=0;i<bands && i<maxBands;++i)if(i*16<=local && local+16<=i*16+32)covered[i]=1;
        };
        const size_t whole=RecognizeOnce(pixels,width,height,stride,left,top,[&](const char16_t* text,size_t x,size_t y,uint32_t fg,uint32_t bg) {mark(text,y);emit(text,x,y,fg,bg);},idle);
        if(!bandsEnabled || height<48 || !pixels || width<8 || !bands)return whole;
        // A large area without any Unifont line (another font, a picture)
        // gets no bands: they cost hundreds of millions of cycles there.
        if(!anyWord && height>128 && !bandsAlways)return whole;
        size_t total=whole;const size_t inked=lastInked_;
        const bool keep=cached_;const size_t keepX=ox_,keepY=oy_;
        sample_=160;
        // Rows of one colour hold no glyph (MarkRows of the whole pass; each
        // band's own pass overwrites it, so it is read first).
        for(size_t i=0;i<bands && i<maxBands;++i)
            if(rowsMarked_>=i*16+32 && inkedRows_[i*16+32]==inkedRows_[i*16])covered[i]=1;
        for(size_t i=0;i<bands && i<maxBands;++i) {
            if(covered[i])continue;
            const size_t y=i*16;
            cached_=false;idle();
            auto band=[&](const char16_t* text,size_t x,size_t yy,uint32_t fg,uint32_t bg) {mark(text,yy);emit(text,x,yy,fg,bg);};
            size_t got=RecognizeOnce(pixels+y*stride,width,32,stride,left,top+y,band,idle);
            if(!got) {
                // A label beside a picture edge (Debian's menu next to its
                // wallpaper curve): groups of changing columns at least 16
                // pixels apart are judged one by one.
                size_t start=SIZE_MAX,last=0,groups=0;
                for(size_t x=1;x<=width && groups<16;++x) {
                    bool ink=false;
                    if(x<width)for(size_t r=0;r<32 && !ink;++r) {const uint32_t* row=pixels+(y+r)*stride;ink=(row[x]&0xffffff)!=(row[x-1]&0xffffff);}
                    if(ink) {if(start==SIZE_MAX)start=x;last=x;}
                    if(start!=SIZE_MAX && (x==width || (!ink && x-last>16))) {
                        const size_t x0=start>=9?start-9:0,x1=last+9<width?last+9:width;
                        if(!(x0==0 && x1==width) && x1-x0>=16) {cached_=false;got+=RecognizeOnce(pixels+y*stride+x0,x1-x0,32,stride,left+x0,top+y,band,idle);}
                        start=SIZE_MAX;++groups;
                    }
                }
            }
            total+=got;
        }
        sample_=600;
        cached_=keep;ox_=keepX;oy_=keepY;if(total==whole)lastInked_=inked;
        return total;
    }
    template<class Emit,class Idle> size_t RecognizeOnce(const uint32_t* pixels,size_t width,size_t height,size_t stride,size_t left,size_t top,Emit emit,Idle idle) {
        lastInked_=0;
        if(!pixels || width<8 || height<16)return 0;
        Prepare();
        MarkRows(pixels,width,height,stride);
        // Grid offset on the screen (x mod 8, y mod 16): keep the cached one
        // when it explains most inked cells, otherwise search all 128. Text
        // is accepted only when at least 40% of the sampled inked cells are
        // exact glyphs: a picture, another font or a wrong frame-buffer
        // geometry yields nothing instead of look-alike punctuation.
        size_t inked=0;
        if(!(cached_ && Score(pixels,width,height,stride,left,top,ox_,oy_,inked,sample_)*10>=inked*6 && inked)) {
            size_t ox=0,oy=0;
            idle();const size_t best=Locate(pixels,width,height,stride,left,top,sample_,ox,oy,inked);idle();
            lastInked_=inked;
            if(best<3 || best*10<inked*4)return 0;
            ox_=ox;oy_=oy;cached_=true;
        }
        size_t recognized=0;
        const size_t firstX=(ox_+8-(left%8))%8,firstY=(oy_+16-(top%16))%16;
        for(size_t y=firstY;y+16<=height;y+=16) {
            if(y>firstY && !((y-firstY)&63))idle();
            if(Blank(y))continue;   // r386: a band of one-colour rows holds no glyph
            char16_t run[256];size_t length=0,runX=0;uint32_t runFg=0,runBg=0;bool open=false;
            auto close=[&]() {
                if(!open)return;
                while(length && run[length-1]==u' ')--length;
                size_t lead=0;while(lead<length && run[lead]==u' ')++lead;
                run[length]=0;
                // r386: on a textured picture "l" can come out as "1" ("He1p",
                // "Too1s"): a 1 between two letters is the letter.
                {auto letter=[](char16_t ch) {return (ch>=u'a' && ch<=u'z') || (ch>=u'A' && ch<=u'Z');};
                 for(size_t i=lead+1;i+1<length;++i)if(run[i]==u'1' && letter(run[i-1]) && letter(run[i+1]))run[i]=u'l';}
                if(length>lead)emit(run+lead,runX+lead*8,top+y,runFg,runBg);
                open=false;length=0;
            };
            for(size_t x=firstX;x+8<=width;x+=8) {
                const Cell cell=Read(pixels+y*stride+x,stride);
                // r386: a background that differs by a few levels (text
                // across a wallpaper's soft edge) continues the run.
                if(open && cell.background!=runBg && Contrast(cell.background,runBg)>=96)close();
                if(!open) {open=true;runX=left+x;runBg=cell.background;runFg=cell.foreground;length=0;}
                if(cell.ink) {runFg=cell.foreground;if(cell.ch!=u' ')++recognized;}
                if(length+1<sizeof(run)/2)run[length++]=cell.ch==char16_t(0xfffd)?u' ':cell.ch;
            }
            close();
        }
        return recognized;
    }
    // Share of exact glyphs (per mille) among up to `sample` inked cells at
    // the best grid offset: tests a candidate frame-buffer geometry.
    size_t Quality(const uint32_t* pixels,size_t width,size_t height,size_t stride,size_t sample) {
        if(!pixels || width<8 || height<16)return 0;
        Prepare();
        MarkRows(pixels,width,height,stride);
        size_t ox=0,oy=0,inked=0;const size_t best=Locate(pixels,width,height,stride,0,0,sample,ox,oy,inked);
        return best<3?0:best*1000/(inked?inked:1);
    }
    // r386: one more 8x16 glyph (a program's own font); exact duplicates of
    // a known glyph with the same code are skipped. False when full.
    bool AddGlyph(uint16_t code,const uint8_t* rows) {
        Prepare();
        const uint32_t hash=Hash(rows);
        for(uint32_t probe=0;probe<tableSize;++probe) {
            const uint16_t slot=table_[(hash+probe)%tableSize];
            if(slot==0xffff)break;
            const uint8_t* g=RowsOf(slot);bool same=true;for(unsigned i=0;i<16;++i)if(g[i]!=rows[i]) {same=false;break;}
            if(same)return true;
        }
        if(extraCount_>=maxExtra)return false;
        bool empty=true;for(unsigned i=0;i<16;++i)if(rows[i])empty=false;
        if(empty)return true;
        for(unsigned i=0;i<16;++i)extraRows_[extraCount_][i]=rows[i];
        extraCodes_[extraCount_]=code;
        for(uint32_t probe=0;probe<tableSize;++probe) {
            auto& slot=table_[(hash+probe)%tableSize];
            if(slot==0xffff) {slot=uint16_t(glyphCount+extraCount_);break;}
        }
        ++extraCount_;return true;
    }
    // Inked cells seen by the last Recognize that rejected the area.
    size_t LastInked() const {return lastInked_;}
    void Forget() {cached_=false;}
private:
    size_t Locate(const uint32_t* pixels,size_t width,size_t height,size_t stride,size_t left,size_t top,size_t sample,size_t& bestX,size_t& bestY,size_t& bestInked) const {
        // Two stages keep this cheap (it runs in the reader's timer, which
        // also feeds audio): all 128 offsets on the first 32 inked cells,
        // then the full sample on the four best offsets.
        struct Candidate {size_t score,ox,oy;};
        Candidate top4[4]={};
        const size_t quick=sample<32?sample:32;
        for(size_t oy=0;oy<16;++oy)for(size_t ox=0;ox<8;++ox) {
            size_t inked=0;const size_t score=Score(pixels,width,height,stride,left,top,ox,oy,inked,quick);
            for(unsigned i=0;i<4;++i)if(score>top4[i].score || (!i && !top4[0].score && !(ox|oy))) {
                for(unsigned j=3;j>i;--j)top4[j]=top4[j-1];
                top4[i]={score,ox,oy};break;
            }
        }
        size_t best=0;bestX=top4[0].ox;bestY=top4[0].oy;bestInked=0;
        for(const auto& candidate:top4) {
            if(!candidate.score && best)continue;
            size_t inked=0;const size_t score=Score(pixels,width,height,stride,left,top,candidate.ox,candidate.oy,inked,sample);
            if(score>best || (!best && inked>bestInked)) {best=score;bestX=candidate.ox;bestY=candidate.oy;bestInked=inked;}
        }
        return best;
    }
    void Prepare() {
        if(prepared_)return;
        for(auto& slot:table_)slot=0xffff;
        for(unsigned i=0;i<glyphCount;++i) {
            const uint32_t hash=Hash(glyphRows[i]);
            for(uint32_t probe=0;probe<tableSize;++probe) {
                auto& slot=table_[(hash+probe)%tableSize];
                if(slot==0xffff) {slot=uint16_t(i);break;}
            }
        }
        prepared_=true;
        for(const auto& v:unifontVariants)AddGlyph(v.code,v.rows);
    }
    static uint32_t Hash(const uint8_t* rows) {
        uint32_t h=2166136261u;for(unsigned i=0;i<16;++i) {h^=rows[i];h*=16777619u;}return h;
    }
    static unsigned Bits(uint8_t value) {unsigned n=0;while(value) {value&=uint8_t(value-1);++n;}return n;}
    // Two-colour reduction of one cell; ink = cell has a second colour.
    Cell Read(const uint32_t* cell,size_t stride) const {
        uint32_t first=cell[0]&0xffffff,second=first;size_t firstCount=0,secondCount=0;bool more=false;
        for(size_t y=0;y<16;++y)for(size_t x=0;x<8;++x) {
            const uint32_t pixel=cell[y*stride+x]&0xffffff;
            if(pixel==first)++firstCount;
            else if(!secondCount || pixel==second) {second=pixel;++secondCount;}
            else more=true;
        }
        Cell result{u' ',second,first,secondCount!=0};
        const uint32_t background=more?first:(firstCount>=secondCount?first:second),foreground=background==first?second:first;  // r386: textured cells: the corner is the reference
        result.background=background;result.foreground=foreground;
        if(!result.ink)return result;
        // r386: ink level for three-colour cells: half the strongest change
        // (the glyph), at least 40 (two wallpaper shapes behind it differ less).
        unsigned inkLevel=40;
        if(more) {unsigned top=0;for(size_t y=0;y<16;++y)for(size_t x=0;x<8;++x) {const unsigned c=Contrast(cell[y*stride+x]&0xffffff,background);if(c>top)top=c;}
            if(top/2>inkLevel)inkLevel=top/2;}
        uint8_t rows[16];
        for(size_t y=0;y<16;++y) {
            uint8_t bits=0;
            // r386: with three or more colours, pixels within a few levels
            // of the background are background (a wallpaper edge behind the
            // glyph); two-colour cells stay exact.
            for(size_t x=0;x<8;++x) {const uint32_t pixel=cell[y*stride+x]&0xffffff;
                if(more?Contrast(pixel,background)>=inkLevel:pixel!=background)bits|=uint8_t(0x80>>x);}
            rows[y]=bits;
        }
        result.ch=Match(rows,more);
        return result;
    }
    char16_t Match(const uint8_t* rows,bool noisy) const {
        const uint32_t hash=Hash(rows);
        for(uint32_t probe=0;probe<tableSize;++probe) {
            const uint16_t slot=table_[(hash+probe)%tableSize];
            if(slot==0xffff)break;
            bool same=true;const uint8_t* g=RowsOf(slot);for(unsigned i=0;i<16;++i)if(g[i]!=rows[i]) {same=false;break;}
            if(same)return char16_t(CodeOf(slot));
        }
        // Bounded nearest match (other Unifont versions, a cursor bar, a
        // stray anti-aliased pixel): at most 6 differing bits of 128 and at
        // most a fifth of the glyph's own pixels, so sparse marks (` ´ ¯ .)
        // never stand for noise.
        unsigned best=7;char16_t found=u'\0';
        for(unsigned i=0;i<glyphCount+extraCount_;++i) {
            unsigned distance=0,bits=0;const uint8_t* g=RowsOf(i);
            for(unsigned r=0;r<16 && distance<best;++r) {distance+=Bits(uint8_t(g[r]^rows[r]));bits+=Bits(g[r]);}
            if(distance<best && distance*5<=bits) {best=distance;found=char16_t(CodeOf(i));}
        }
        (void)noisy;
        return found?found:char16_t(0xfffd);
    }
    // Exact matches for a grid offset over a bounded sample of cells.
    size_t Score(const uint32_t* pixels,size_t width,size_t height,size_t stride,size_t left,size_t top,size_t ox,size_t oy,size_t& inked,size_t sample) const {
        const size_t firstX=(ox+8-(left%8))%8,firstY=(oy+16-(top%16))%16;
        size_t matches=0,sampled=0;inked=0;
        for(size_t y=firstY;y+16<=height && sampled<sample;y+=16) {
            if(Blank(y))continue;
            for(size_t x=firstX;x+8<=width && sampled<sample;x+=8) {
                const Cell cell=ReadExact(pixels+y*stride+x,stride);
                if(!cell.ink)continue;
                // r386: box and block elements locate no grid: a selection
                // bar cut at the wrong offset matches block glyphs exactly
                // (U+2587) and outvoted the letters on it.
                if(cell.ch>=0x2500 && cell.ch<=0x259f)continue;
                ++inked;++sampled;if(cell.ch!=u'\0')++matches;
            }
        }
        return matches;
    }
    // r386: sum of channel differences of two colours.
    static unsigned Contrast(uint32_t a,uint32_t b) {
        unsigned d=0;for(unsigned s=0;s<24;s+=8) {const int x=int((a>>s)&255)-int((b>>s)&255);d+=unsigned(x<0?-x:x);}
        return d;
    }
    Cell ReadExact(const uint32_t* cell,size_t stride) const {
        uint32_t first=cell[0]&0xffffff,second=first;size_t firstCount=0,secondCount=0;
        for(size_t y=0;y<16;++y)for(size_t x=0;x<8;++x) {
            const uint32_t pixel=cell[y*stride+x]&0xffffff;
            if(pixel==first)++firstCount;
            else if(!secondCount || pixel==second) {second=pixel;++secondCount;}
            else {
                // r386: three or more colours. A soft picture area (wallpaper
                // curve, gradient: all within a few levels) counts as no ink,
                // or it would outvote the text beside it; anything else is an
                // inked cell that is no glyph.
                bool soft=true;
                for(size_t yy=0;yy<16 && soft;++yy)soft=Contrast(cell[yy*stride+(yy*5)%8]&0xffffff,first)<80;  // 16 samples: cheap on wallpapers
                if(soft)return {u' ',0,0,false};
                // r386: text over a textured picture (Ventoy's theme): ink is
                // what differs from the cell's corner by more than half the
                // strongest change (and at least 120); the rest is picture.
                unsigned top=0;
                for(size_t yy=0;yy<16;++yy)for(size_t xx=0;xx<8;++xx) {const unsigned c=Contrast(cell[yy*stride+xx]&0xffffff,first);if(c>top)top=c;}
                if(top<120)return {u'\0',0,0,true};
                uint8_t rows[16];
                for(size_t yy=0;yy<16;++yy) {uint8_t bits=0;for(size_t xx=0;xx<8;++xx)if(Contrast(cell[yy*stride+xx]&0xffffff,first)*2>top)bits|=uint8_t(0x80>>xx);rows[yy]=bits;}
                const uint32_t hash=Hash(rows);
                for(uint32_t probe=0;probe<tableSize;++probe) {
                    const uint16_t slot=table_[(hash+probe)%tableSize];
                    if(slot==0xffff)break;
                    bool same=true;const uint8_t* g=RowsOf(slot);for(unsigned i=0;i<16;++i)if(g[i]!=rows[i]) {same=false;break;}
                    if(same)return {char16_t(CodeOf(slot)),0,first,true};
                }
                return {u'\0',0,0,true};
            }
        }
        if(!secondCount)return {u' ',first,first,false};
        if(Contrast(first,second)<80)return {u' ',first,first,false};
        const uint32_t background=firstCount>=secondCount?first:second;
        uint8_t rows[16];
        for(size_t y=0;y<16;++y) {
            uint8_t bits=0;
            for(size_t x=0;x<8;++x)if((cell[y*stride+x]&0xffffff)!=background)bits|=uint8_t(0x80>>x);
            rows[y]=bits;
        }
        const uint32_t hash=Hash(rows);
        for(uint32_t probe=0;probe<tableSize;++probe) {
            const uint16_t slot=table_[(hash+probe)%tableSize];
            if(slot==0xffff)break;
            bool same=true;const uint8_t* g=RowsOf(slot);for(unsigned i=0;i<16;++i)if(g[i]!=rows[i]) {same=false;break;}
            if(same)return {char16_t(CodeOf(slot)),0,background,true};
        }
        // r386: an unmatched cell of whole horizontal stripes or one
        // repeated column pattern is the edge of a bar or a frame (a theme's
        // selection bar), not a letter: it must not outvote the text on it.
        bool stripes=true,columns=true;
        for(unsigned i=0;i<16;++i) {stripes=stripes && (rows[i]==0 || rows[i]==0xff);columns=columns && rows[i]==rows[0];}
        return {u'\0',0,background,!(stripes || columns)};
    }
    // r386: rows of a single colour, once per call, as a prefix count: the
    // 128 grid offsets of Locate used to read every empty cell of a large
    // screen again (OpenCore at 2560x1600 lost its keys meanwhile).
    void MarkRows(const uint32_t* pixels,size_t width,size_t height,size_t stride) {
        rowsMarked_=height<=maxMarkedRows?height:0;
        if(!rowsMarked_)return;
        inkedRows_[0]=0;
        for(size_t y=0;y<height;++y) {
            const uint32_t* row=pixels+y*stride;const uint32_t first=row[0]&0xffffff;bool ink=false;
            for(size_t x=1;x<width && !ink;++x)ink=(row[x]&0xffffff)!=first;
            inkedRows_[y+1]=uint16_t(inkedRows_[y]+(ink?1:0));
        }
    }
    bool Blank(size_t y) const {return rowsMarked_ && y+16<=rowsMarked_ && inkedRows_[y+16]==inkedRows_[y];}
    static constexpr size_t maxMarkedRows=4096;
    uint16_t inkedRows_[maxMarkedRows+1]={};size_t rowsMarked_=0;
    // r386: glyphs of the running program's own font (GRUB's unicode.pf2:
    // Ventoy's differs from the built-in Unifont in "-" and "t").
    static constexpr unsigned maxExtra=1024;
    uint8_t extraRows_[maxExtra][16]={};uint16_t extraCodes_[maxExtra]={};unsigned extraCount_=0;
    const uint8_t* RowsOf(uint32_t slot) const {return slot<glyphCount?glyphRows[slot]:extraRows_[slot-glyphCount];}
    uint16_t CodeOf(uint32_t slot) const {return slot<glyphCount?glyphCodes[slot]:extraCodes_[slot-glyphCount];}
    static constexpr uint32_t tableSize=4096;
    uint16_t table_[tableSize]={};
    bool prepared_=false,cached_=false;
    size_t ox_=0,oy_=0,lastInked_=0;
    size_t sample_=600;  // r386: inked cells judged per grid search (160 in bands)
};
