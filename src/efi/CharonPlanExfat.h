// Charon r410 (helper bd): the shared data partition of a plan gets an exFAT file system, written in place by
// step 0 before any system is installed, so that every system of the plan finds it ready (ready images start for the
// first time only at the end of a plan; an installer's environment has no mkfs.exfat). Pure code: the caller gives a
// sector writer. Host tested: tests/charon-r409-plan-tests.cpp (TestExfat).
// Source: Microsoft, "exFAT file system specification",
//   https://learn.microsoft.com/en-us/windows/win32/fileio/exfat-specification
//   (3.1 Main Boot Sector, 3.2 Main Extended Boot Sectors, 3.4 Main Boot Checksum, 4.1 FAT entries, 7.1 Allocation
//   Bitmap entry, 7.2 Up-case Table entry and its compressed form, 7.3 Volume Label entry).
// Layout written: boot region (sectors 0-11) and its backup (12-23); one FAT at 1 MiB; the cluster heap behind it,
// aligned to a cluster: the allocation bitmap from cluster 2, the up-case table, the root directory (one cluster).
// Cluster size: 4 KiB up to 256 MiB, 32 KiB up to 32 GiB, 128 KiB above (the sizes Windows' format proposes).
// GPL-2.0-or-later.
#include "CharonPlanModel.h"

