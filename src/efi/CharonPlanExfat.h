constexpr size_t kUpcaseEntries = sizeof(kUpcase) / sizeof(kUpcase[0]);
constexpr uint32_t kSector = 512;
constexpr uint32_t kFatOffset = 2048;          // 1 MiB into the partition
constexpr size_t kMaxCluster = 128 * 1024;

struct Geometry {
	uint64_t sectors;        // VolumeLength
	uint32_t fatOffset, fatLength, heapOffset, clusterCount;
	uint8_t spcShift;        // SectorsPerClusterShift
	uint32_t bitmapBytes, bitmapClusters, upcaseCluster, rootCluster;
};
// The writer of the caller: `bytes` (a multiple of 512) at partition-relative sector `lba`.
struct Sink {
	void* context;
	bool (*write)(void* context, uint64_t lba, const uint8_t* data, size_t bytes);
};

inline uint32_t Rotate(uint32_t sum, uint8_t byte) { return ((sum & 1) ? 0x80000000u : 0u) + (sum >> 1) + byte; }
// 3.4: over the 11 sectors of the boot region, without VolumeFlags (106, 107) and PercentInUse (112).
inline uint32_t BootChecksum(const uint8_t* region)
{
	uint32_t sum = 0;
	for (uint32_t i = 0; i < 11 * kSector; i++)
		if (i != 106 && i != 107 && i != 112)
			sum = Rotate(sum, region[i]);
	return sum;
}
inline uint32_t TableChecksum(const uint8_t* data, size_t bytes)
{
	uint32_t sum = 0;
	for (size_t i = 0; i < bytes; i++)
		sum = Rotate(sum, data[i]);
	return sum;
}
inline void Put16(uint8_t* p, uint32_t v) { p[0] = uint8_t(v); p[1] = uint8_t(v >> 8); }
inline void Put32(uint8_t* p, uint32_t v) { for (int i = 0; i < 4; i++) p[i] = uint8_t(v >> (8 * i)); }
inline void Put64(uint8_t* p, uint64_t v) { for (int i = 0; i < 8; i++) p[i] = uint8_t(v >> (8 * i)); }

// False: the partition is too small (under 64 MiB) or too large for 32-bit cluster numbers.
inline bool Compute(uint64_t sectors, Geometry& g)
{
	for (uint8_t* p = reinterpret_cast<uint8_t*>(&g); p < reinterpret_cast<uint8_t*>(&g + 1); p++)
		*p = 0;
	if (sectors < (uint64_t(64) << 11))
		return false;
	const uint64_t bytes = sectors * kSector;
	g.spcShift = bytes <= (uint64_t(256) << 20) ? 3 : bytes <= (uint64_t(32) << 30) ? 6 : 8;
	const uint32_t spc = uint32_t(1) << g.spcShift;
	g.sectors = sectors;
	g.fatOffset = kFatOffset;
	uint64_t clusters = (sectors - kFatOffset) >> g.spcShift;
	if (clusters > 0xFFFFFFF5ull)
		return false;
	g.fatLength = uint32_t(((clusters + 2) * 4 + kSector - 1) / kSector);
	const uint64_t heap = (uint64_t(kFatOffset) + g.fatLength + spc - 1) / spc * spc;
	if (heap >= sectors)
		return false;
	clusters = (sectors - heap) >> g.spcShift;   // fewer than before: the FAT above is long enough
	g.heapOffset = uint32_t(heap);
	g.clusterCount = uint32_t(clusters);
	const uint32_t clusterBytes = kSector << g.spcShift;
	g.bitmapBytes = (g.clusterCount + 7) / 8;
	g.bitmapClusters = (g.bitmapBytes + clusterBytes - 1) / clusterBytes;
	g.upcaseCluster = 2 + g.bitmapClusters;
	g.rootCluster = g.upcaseCluster + 1;   // the table (1660 bytes) fits in one cluster of any size used here
	return g.clusterCount > g.rootCluster;
}

// Writes the whole file system. The main boot sector goes last: until it is written the partition is not an exFAT
// volume, so a failure on the way leaves nothing that looks valid. `label`: up to 11 UTF-16 units.
inline bool Format(const Sink& sink, uint64_t partitionLba, uint64_t sectors, const char16_t* label, uint32_t serial)
{
	Geometry g;
	if (!Compute(sectors, g))
		return false;
	const uint32_t clusterBytes = kSector << g.spcShift;
	alignas(16) static uint8_t buffer[kMaxCluster];
	auto clear = [&]() { for (size_t i = 0; i < clusterBytes; i++) buffer[i] = 0; };
	auto clusterLba = [&](uint32_t cluster) { return uint64_t(g.heapOffset) + (uint64_t(cluster - 2) << g.spcShift); };
	const uint32_t used = g.rootCluster - 1;   // clusters 2 .. rootCluster
	// The FAT: media and end entries, one chain each for the bitmap, the table and the root directory; zero after.
	for (uint32_t done = 0; done < g.fatLength;) {
		uint32_t count = g.fatLength - done;
		if (count > clusterBytes / kSector)
			count = clusterBytes / kSector;
		clear();
		if (done == 0) {
			Put32(buffer, 0xFFFFFFF8u);
			Put32(buffer + 4, 0xFFFFFFFFu);
			for (uint32_t c = 2; c <= g.rootCluster; c++) {
				const bool last = c == g.upcaseCluster - 1 || c == g.upcaseCluster || c == g.rootCluster;
				Put32(buffer + 4 * c, last ? 0xFFFFFFFFu : c + 1);
			}
		}
		if (!sink.write(sink.context, g.fatOffset + done, buffer, size_t(count) * kSector))
			return false;
		done += count;
	}
	// The allocation bitmap: the clusters in use.
	for (uint32_t k = 0; k < g.bitmapClusters; k++) {
		clear();
		for (uint32_t bit = 0; bit < used; bit++) {
			const uint64_t at = uint64_t(bit) / 8;
			if (at >= uint64_t(k) * clusterBytes && at < uint64_t(k + 1) * clusterBytes)
				buffer[at - uint64_t(k) * clusterBytes] |= uint8_t(1u << (bit % 8));
		}
		if (!sink.write(sink.context, clusterLba(2 + k), buffer, clusterBytes))
			return false;
	}
	// The up-case table.
	clear();
	for (size_t i = 0; i < kUpcaseEntries; i++)
		Put16(buffer + 2 * i, kUpcase[i]);
	const uint32_t tableBytes = uint32_t(kUpcaseEntries * 2);
	const uint32_t tableSum = TableChecksum(buffer, tableBytes);
	if (!sink.write(sink.context, clusterLba(g.upcaseCluster), buffer, clusterBytes))
		return false;
	// The root directory: volume label, allocation bitmap, up-case table; then the end of the directory.
	clear();
	uint8_t* e = buffer;
	e[0] = 0x83;
	size_t n = 0;
	while (label && label[n] && n < 11) {
		Put16(e + 2 + 2 * n, label[n]);
		n++;
	}
	e[1] = uint8_t(n);
	e += 32;
	e[0] = 0x81;
	Put32(e + 20, 2);
	Put64(e + 24, g.bitmapBytes);
	e += 32;
	e[0] = 0x82;
	Put32(e + 4, tableSum);
	Put32(e + 20, g.upcaseCluster);
	Put64(e + 24, tableBytes);
	if (!sink.write(sink.context, clusterLba(g.rootCluster), buffer, clusterBytes))
		return false;
	// The boot region, twelve sectors: boot sector, eight extended boot sectors, OEM parameters, reserved, checksum.
	alignas(16) static uint8_t region[12 * kSector];
	for (auto& b : region)
		b = 0;
	uint8_t* boot = region;
	boot[0] = 0xEB; boot[1] = 0x76; boot[2] = 0x90;
	const char name[] = "EXFAT   ";
	for (int i = 0; i < 8; i++)
		boot[3 + i] = uint8_t(name[i]);
	Put64(boot + 64, partitionLba);
	Put64(boot + 72, g.sectors);
	Put32(boot + 80, g.fatOffset);
	Put32(boot + 84, g.fatLength);
	Put32(boot + 88, g.heapOffset);
	Put32(boot + 92, g.clusterCount);
	Put32(boot + 96, g.rootCluster);
	Put32(boot + 100, serial);
	Put16(boot + 104, 0x0100);
	boot[108] = 9;
	boot[109] = g.spcShift;
	boot[110] = 1;
	boot[111] = 0x80;
	boot[112] = uint8_t(uint64_t(used) * 100 / g.clusterCount);
	for (int i = 120; i < 510; i++)
		boot[i] = 0xF4;
	boot[510] = 0x55; boot[511] = 0xAA;
	for (int s = 1; s <= 8; s++) {
		region[s * kSector + 510] = 0x55;
		region[s * kSector + 511] = 0xAA;
	}
	const uint32_t sum = BootChecksum(region);
	for (uint32_t i = 0; i < kSector; i += 4)
		Put32(region + 11 * kSector + i, sum);
	if (!sink.write(sink.context, 12, region, 12 * kSector))   // the backup first
		return false;
	if (!sink.write(sink.context, 1, region + kSector, 11 * kSector))
		return false;
	return sink.write(sink.context, 0, region, kSector);
}

